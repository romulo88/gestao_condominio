package com.condominiogestao.ronda;

public enum TipoRonda {
    /** Ronda em volta do condomínio, com rota combinada antes com o síndico. */
    normal,
    /** Rondista acompanha entregador/caminhão de mudança etc. até a casa do morador e
     * garante o retorno dele pra fora do condomínio (ou leva alguém de moto até algum lugar). */
    acompanhamento
}
